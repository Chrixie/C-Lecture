// All programs start in main()
int main()
{
	// DECLARE variables
	int number1; // Declare number1 as an integer variable
	int number2;
	int result;


	// DEFINE variables
	number1 = 10; // Assign variable called number1 to the integer value 10
	number2 = 7;


	// DEFINE result as ADDITION of number1 and number 2 
	result = number1 * number2;


	// EXIT program
	return 0;

}